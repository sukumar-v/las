import { describe, expect, it } from "vitest";
import { Store } from "../src/index.js";
import { BASE_THEME } from "@las/schema";

describe("store", () => {
  it("migrates and round-trips the main tables", () => {
    const s = new Store(":memory:");
    expect(s.db.version).toBe(1);
    const learner = s.getOrCreateLearner();
    expect(s.getOrCreateLearner().id).toBe(learner.id);
    const model = s.saveSkillModel({ skill: "juggling", name: "Juggling", version: 1, source: "generated" } as any, true);
    expect(model.validatedAt).toBeTruthy();
    const again = s.saveSkillModel({ ...model.model, id: model.id } as any, true);
    expect(again.version).toBe(2);
    expect(s.findSkillModel("Juggling")?.id).toBe(model.id);
    const sk = s.createEnrollment(learner.id, model.id);
    expect(s.resolveEnrollment("juggling")?.id).toBe(sk.id);
    expect(s.resolveEnrollment(model.id)?.id).toBe(sk.id);
    s.setIntent(sk.id, ["fun"], "Juggling at parties");
    expect(s.getIntent(sk.id)?.why).toEqual(["fun"]);
    s.setConstraints({ enrollmentId: sk.id, minutesPerWeek: 120, access: ["balls"], injuries: [], schedule: { sessionsPerWeek: 3, minutesEach: 40, days: [0, 2, 4] } });
    expect(s.getConstraints(sk.id)?.minutesPerWeek).toBe(120);
    const m = s.addMilestone({ enrollmentId: sk.id, title: "Three-ball cascade", ladderStep: 2, proof: { engine: "movement" }, kind: "quick", estimateWeeks: 4 });
    expect(s.activeMilestone(sk.id)?.id).toBe(m.id);
    s.addMilestone({ enrollmentId: sk.id, title: "Next", ladderStep: 3, proof: {} });
    expect(s.getMilestone(m.id)?.status).toBe("replaced");
    s.setMastery(sk.id, "cascade", 0.4, 3, true);
    expect(s.getMastery(sk.id).get("cascade")?.pKnown).toBe(0.4);
    const ses = s.createSession({ enrollmentId: sk.id, plan: { blocks: [] }, plannedAt: new Date().toISOString() });
    const att = s.createAttempt({ sessionId: ses.id, enrollmentId: sk.id, kind: "perform", engine: "movement", attemptNo: 1 });
    s.setAttemptAnalysis(att.id, { engine: "movement", quality: { ok: true, issues: [] }, metrics: {}, markers: [], mistakes: [], criteria: {}, keyFrames: [], version: "t", precision: "full" }, "/tmp/x.webm");
    expect(s.getAttempt(att.id)?.analysis?.quality.ok).toBe(true);
    s.setMistakeState({ enrollmentId: sk.id, mistakeId: "drop", state: "detected", disputedCount: 0, cleanStreak: 0, seenCount: 1 });
    expect(s.getMistakeStates(sk.id).get("drop")?.state).toBe("detected");
    const c = s.addCheckin({ enrollmentId: sk.id, kind: "missed", dueAt: new Date().toISOString(), payload: {} });
    expect(s.listCheckins(sk.id, { pending: true }).map((x) => x.id)).toEqual([c.id]);
    s.updateCheckin(c.id, { answeredAt: new Date().toISOString(), answer: "move" });
    expect(s.listCheckins(sk.id, { pending: true })).toEqual([]);
    s.logTime(sk.id, 30, "session", "Technique");
    expect(s.timeSince(sk.id, "2000-01-01").byCategory.Technique).toBe(30);
    s.setSetting("consent.local", true);
    expect(s.getSetting("consent.local", false)).toBe(true);
    const tok = s.createPairingToken();
    expect(s.consumePairingToken(tok, "phone")).toBe(true);
    expect(s.consumePairingToken(tok, "phone")).toBe(false);
    const exported = s.exportAll({ enrollmentId: sk.id });
    expect(exported.attempt.length).toBe(1);
    const media = s.deleteEnrollment(sk.id);
    expect(media).toEqual(["/tmp/x.webm"]);
    expect(s.getEnrollment(sk.id)).toBeUndefined();
    s.close();
  });
  it("scopes themes per learner and per skill", () => {
    const s = new Store(":memory:");
    const l = s.getOrCreateLearner();
    const t1 = s.saveTheme(l.id, { ...BASE_THEME, id: undefined, name: "Calm" }, true);
    const t2 = s.saveTheme(l.id, { ...BASE_THEME, id: undefined, name: "Terminal" }, true);
    s.setThemeScope(l.id, t1.id, null);
    expect(s.activeTheme(l.id)?.name).toBe("Calm");
    s.setThemeScope(l.id, t2.id, "sk_rust");
    expect(s.activeTheme(l.id, "sk_rust")?.name).toBe("Terminal");
    expect(s.activeTheme(l.id, "sk_yoga")?.name).toBe("Calm");
    s.clearThemeScope(l.id, "sk_rust");
    expect(s.activeTheme(l.id, "sk_rust")?.name).toBe("Calm");
    expect(s.listThemes(l.id).length).toBe(2);
  });
});
