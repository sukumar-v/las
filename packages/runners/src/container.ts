/**
 * The container runner: Podman (preferred) or Docker Engine, both Apache-2.0 and installed by the
 * learner. One container per run, with no network, a memory cap, a read-only root, the learner's
 * files mounted read-only at /src and copied into a tmpfs at /work. A generated sh script runs the
 * same steps as the local runner, each under `timeout`, and prints every step's output base64-encoded
 * between markers, so the node side can split it back into step results.
 * Images are the language table's (official Docker Hub images where one exists), pulled on first use.
 */
import { spawnSync } from "node:child_process";
import { chmod, mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import type { TestSpec } from "@las/schema";
import { assembleResult, buildHarness, planSteps, runnerFailure, type PlannedStep } from "./harness.js";
import { LANGUAGE_TABLE } from "./languages.js";
import { exec, which } from "./process.js";
import type { RunResult, StepResult } from "./types.js";

export interface ContainerOptions {
  runtime: "podman" | "docker";
  /** overrides spec.limits.time_s */
  timeoutS?: number;
  /** overrides spec.limits.memory_mb for the program; the container itself gets at least 512 MB so builds fit */
  memoryMb?: number;
  /** use another image than the table's */
  image?: string;
  /** pull the image when it is missing (default true) */
  pull?: boolean;
}

/** Podman or Docker, whichever answers first; undefined when neither works. */
export function detectContainerRuntime(): "podman" | "docker" | undefined {
  for (const rt of ["podman", "docker"] as const) {
    if (!which(rt)) continue;
    const r = spawnSync(rt, ["info"], { stdio: "ignore", timeout: 15000 });
    if (r.status === 0) return rt;
  }
  return undefined;
}

const shq = (s: string) => "'" + s.replace(/'/g, "'\\''") + "'";
const varName = (id: string) => "las_ok_" + id.replace(/\W/g, "_");

/** The sh script that runs every step inside the container. */
export function containerScript(steps: PlannedStep[], opts: { vmLimitKb: number; src?: string; work?: string; tmp?: string }): string {
  // the folders are options only so tests can run the script with plain sh, outside a container
  const src = opts.src ?? "/src";
  const work = opts.work ?? "/work";
  const tmp = opts.tmp ?? "/tmp";
  const lines = [
    "#!/bin/sh",
    "# Generated by LAS: copies the read-only sources into /work, then runs each step with its time limit.",
    `cp -R ${src}/. ${work}/ || exit 90`,
    `cd ${work} || exit 91`,
    "las_enc() { if command -v base64 >/dev/null 2>&1; then printf 'b64:'; head -c 1000000 \"$1\" | base64 | tr -d '\\n'; else printf 'hex:'; head -c 1000000 \"$1\" | od -An -v -tx1 | tr -d ' \\n'; fi; }",
    "las_step() {",
    '  las_id=$1; las_limit=$2; las_in=$3; las_merge=$4; las_vm=$5; shift 5',
    "  las_start=$(date +%s)",
    '  if command -v timeout >/dev/null 2>&1; then set -- timeout -s KILL "$las_limit" "$@"; fi',
    '  if [ "$las_merge" = 1 ]; then',
    `    ( if [ "$las_vm" != 0 ]; then ulimit -v "$las_vm" 2>/dev/null; fi; exec "$@" ) < "$las_in" > ${tmp}/las_out 2>&1`,
    "  else",
    `    ( if [ "$las_vm" != 0 ]; then ulimit -v "$las_vm" 2>/dev/null; fi; exec "$@" ) < "$las_in" > ${tmp}/las_out 2> ${tmp}/las_err`,
    "  fi",
    "  las_code=$?",
    "  las_end=$(date +%s)",
    '  echo "##LAS## step $las_id $las_code $((las_end - las_start))"',
    `  echo "##LAS## out $(las_enc ${tmp}/las_out)"`,
    `  if [ "$las_merge" = 1 ]; then echo "##LAS## err "; else echo "##LAS## err $(las_enc ${tmp}/las_err)"; fi`,
    `  rm -f ${tmp}/las_out ${tmp}/las_err`,
    "}"
  ];
  for (const s of steps) {
    const input = s.stdin !== undefined ? `${src}/.las_in/${s.id}.txt` : "/dev/null";
    const call = `las_step ${s.id} ${s.timeoutS} ${input} ${s.merge ? 1 : 0} ${s.limited ? opts.vmLimitKb : 0} ${s.argv.map(shq).join(" ")}; [ "$las_code" = 0 ] && ${varName(s.id)}=1`;
    if (!s.after.length) lines.push(call);
    else lines.push(`if ${s.after.map((a) => `[ "$${varName(a)}" = 1 ]`).join(" && ")}; then ${call}; else echo "##LAS## skip ${s.id}"; fi`);
  }
  lines.push("exit 0", "");
  return lines.join("\n");
}

const SIGNALS: Record<number, string> = { 4: "SIGILL", 6: "SIGABRT", 7: "SIGBUS", 8: "SIGFPE", 9: "SIGKILL", 11: "SIGSEGV", 15: "SIGTERM" };

function decode(s: string): string {
  const v = s.trim();
  if (v.startsWith("b64:")) return Buffer.from(v.slice(4), "base64").toString("utf8");
  if (v.startsWith("hex:")) return Buffer.from(v.slice(4), "hex").toString("utf8");
  return "";
}

/** Splits the script's output back into step results. */
export function parseContainerOutput(stdout: string, steps: PlannedStep[]): Record<string, StepResult> {
  const byId = new Map(steps.map((s) => [s.id, s]));
  const results: Record<string, StepResult> = {};
  let cur: { id: string; code: number; secs: number; out?: string } | undefined;
  for (const line of stdout.split("\n")) {
    let m: RegExpExecArray | null;
    if ((m = /^##LAS## step (\S+) (\d+) (\d+)\s*$/.exec(line))) cur = { id: m[1], code: Number(m[2]), secs: Number(m[3]) };
    else if ((m = /^##LAS## skip (\S+)\s*$/.exec(line))) results[m[1]] = { code: null, stdout: "", stderr: "", timedOut: false, ms: 0, skipped: true };
    else if (cur && (m = /^##LAS## out ?(.*)$/.exec(line))) cur.out = decode(m[1]);
    else if (cur && (m = /^##LAS## err ?(.*)$/.exec(line))) {
      const limit = byId.get(cur.id)?.timeoutS ?? Infinity;
      const timedOut = (cur.code === 124 || cur.code === 137) && cur.secs >= limit - 1;
      const sig = cur.code > 128 && !timedOut ? cur.code - 128 : 0;
      results[cur.id] = {
        code: sig ? null : cur.code,
        signal: sig ? (SIGNALS[sig] ?? `signal ${sig}`) : null,
        stdout: cur.out ?? "",
        stderr: decode(m[1]),
        timedOut,
        ms: cur.secs * 1000
      };
      cur = undefined;
    }
  }
  return results;
}

export async function runContainer(spec: TestSpec, files: Record<string, string>, opts: ContainerOptions): Promise<RunResult> {
  const def = LANGUAGE_TABLE[spec.language];
  const image = opts.image ?? def.image;
  if (!image) return runnerFailure(spec, "container", `no container image is known for ${def.label}`);
  if (!which(opts.runtime)) return runnerFailure(spec, "container", `${opts.runtime} is not installed`);
  const run: TestSpec = opts.timeoutS ? { ...spec, limits: { ...spec.limits, time_s: opts.timeoutS } } : spec;
  const memoryMb = opts.memoryMb ?? spec.limits.memory_mb;
  const tool = (opts.image ? undefined : def.imageTool) ?? def.toolchains[0].tool;
  const built = buildHarness(run, files, { tool, memoryMb });
  const plan = built.command;
  const steps = planSteps(run, plan);

  const dir = await mkdtemp(join(tmpdir(), "las-box-"));
  const name = `las-run-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
  try {
    const all: Record<string, string> = { ...built.files, "__las_run.sh": containerScript(steps, { vmLimitKb: plan.vmLimit ? memoryMb * 1024 : 0 }) };
    for (const s of steps) if (s.stdin !== undefined) all[`.las_in/${s.id}.txt`] = s.stdin;
    for (const [p, content] of Object.entries(all)) {
      const full = join(dir, p);
      await mkdir(dirname(full), { recursive: true });
      await writeFile(full, content);
    }
    // the container's user may differ from ours, and runs without capabilities: make the copy world-readable
    await chmodTree(dir);

    const env = { LANG: "C.UTF-8", HOME: "/work", TMPDIR: "/tmp", ...plan.env };
    const argv = [
      opts.runtime,
      "run",
      "--rm",
      "--name",
      name,
      "--network",
      "none",
      "--memory",
      `${Math.max(memoryMb, 512)}m`,
      "--pids-limit",
      "512",
      "--read-only",
      "--cap-drop",
      "ALL",
      "--security-opt",
      "no-new-privileges",
      "--tmpfs",
      "/work:rw,exec,size=1g",
      "--tmpfs",
      "/tmp:rw,exec,size=256m",
      "-v",
      `${dir}:/src:ro`,
      "-w",
      "/work",
      ...Object.entries(env).flatMap(([k, v]) => ["-e", `${k}=${v}`]),
      `--pull=${opts.pull === false ? "never" : "missing"}`,
      image,
      "sh",
      "/src/__las_run.sh"
    ];
    const total = steps.reduce((s, x) => s + x.timeoutS, 0) + 60 + (opts.pull === false ? 0 : 600);
    const r = await exec(argv, { cwd: dir, env: { PATH: process.env.PATH ?? "", HOME: process.env.HOME ?? "", ...(process.env.XDG_RUNTIME_DIR ? { XDG_RUNTIME_DIR: process.env.XDG_RUNTIME_DIR } : {}), ...(process.env.DOCKER_HOST ? { DOCKER_HOST: process.env.DOCKER_HOST } : {}) }, timeoutS: total });
    if (r.timedOut) spawnSync(opts.runtime, ["rm", "-f", name], { stdio: "ignore", timeout: 30000 });
    if (r.spawnError) return runnerFailure(spec, "container", r.spawnError);
    const results = parseContainerOutput(r.stdout, steps);
    if (!Object.keys(results).length && steps.length) {
      const why = r.timedOut ? `the container did not finish within ${total} s` : (r.stderr.trim().split("\n").slice(-3).join(" ") || `${opts.runtime} exited with code ${r.code}`);
      return runnerFailure(spec, "container", why);
    }
    return assembleResult(run, plan, results, "container");
  } finally {
    await rm(dir, { recursive: true, force: true }).catch(() => {});
  }
}

async function chmodTree(dir: string) {
  const { readdir } = await import("node:fs/promises");
  await chmod(dir, 0o755);
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) await chmodTree(p);
    else await chmod(p, 0o644);
  }
}
